package lts

import (
	"fmt"
	"sort"
	"strings"

	"github.com/xiongnemo/anima/internal/ast"
	"github.com/xiongnemo/anima/internal/sema"
)

// ExportFSP generates Magee & Kramer LTSA-compatible .fsp notation for all machines,
// properties, progress sets, and systems in the program.
func ExportFSP(info *sema.ProgramInfo) string {
	var sb strings.Builder
	sb.WriteString("// Auto-generated by Anima (FSP/LTSA Exporter)\n\n")

	for _, d := range info.Program.Decls {
		switch m := d.(type) {
		case *ast.MachineDecl:
			comp, err := CompileMachine(m, info)
			if err != nil {
				continue
			}
			writeFSPProcess(&sb, strings.ToUpper(m.Name), comp)
			sb.WriteString("\n")
		case *ast.WorkflowDecl:
			comp := CompileWorkflowLTS(m)
			writeFSPProcess(&sb, strings.ToUpper(m.Name), comp)
			sb.WriteString("\n")
		case *ast.PropertyDecl:
			sb.WriteString(fmt.Sprintf("property %s = %s,\n", strings.ToUpper(m.Name), sanitizeFSPState(m.States[0].Name)))
			for idx, st := range m.States {
				sname := sanitizeFSPState(st.Name)
				sep := ","
				if idx == len(m.States)-1 {
					sep = "."
				}
				if len(st.Transitions) == 0 {
					sb.WriteString(fmt.Sprintf("%s = END%s\n", sname, sep))
					continue
				}
				var alts []string
				for _, tr := range st.Transitions {
					alts = append(alts, fmt.Sprintf("%s -> %s", sanitizeFSPAct(tr.Action), sanitizeFSPState(tr.TargetState)))
				}
				sb.WriteString(fmt.Sprintf("%s = (%s)%s\n", sname, strings.Join(alts, " | "), sep))
			}
			sb.WriteString("\n")
		case *ast.ProgressDecl:
			var acts []string
			for _, a := range m.Actions {
				acts = append(acts, sanitizeFSPAct(a))
			}
			sb.WriteString(fmt.Sprintf("progress %s = {%s}\n\n", strings.ToUpper(m.Name), strings.Join(acts, ", ")))
		case *ast.SystemDecl:
			var parts []string
			for _, inst := range m.Instances {
				p := fmt.Sprintf("%s:%s", inst.Name, strings.ToUpper(inst.TypeName))
				if len(inst.Relabels) > 0 {
					var rbs []string
					for _, r := range inst.Relabels {
						rbs = append(rbs, fmt.Sprintf("%s/%s", sanitizeFSPAct(r.To), sanitizeFSPAct(r.From)))
					}
					p += "/{" + strings.Join(rbs, ", ") + "}"
				}
				parts = append(parts, p)
			}
			sb.WriteString(fmt.Sprintf("||%s = (%s)", strings.ToUpper(m.Name), strings.Join(parts, " || ")))
			if len(m.Hide) > 0 {
				var hs []string
				for _, h := range m.Hide {
					hs = append(hs, sanitizeFSPAct(h))
				}
				sb.WriteString(fmt.Sprintf(" \\ {%s}", strings.Join(hs, ", ")))
			}
			sb.WriteString(".\n\n")
		}
	}
	return sb.String()
}

func writeFSPProcess(sb *strings.Builder, name string, comp *ComponentLTS) {
	if len(comp.States) == 0 {
		return
	}
	sb.WriteString(fmt.Sprintf("%s = %s,\n", name, sanitizeFSPState(comp.States[comp.Init])))
	for i, stLabel := range comp.States {
		sname := sanitizeFSPState(stLabel)
		sep := ","
		if i == len(comp.States)-1 {
			sep = "."
		}
		edges := comp.Edges[i]
		if len(edges) == 0 {
			if comp.Terminal[i] {
				sb.WriteString(fmt.Sprintf("%s = END%s\n", sname, sep))
			} else {
				sb.WriteString(fmt.Sprintf("%s = STOP%s\n", sname, sep))
			}
			continue
		}
		var alts []string
		sortedEdges := append([]Edge{}, edges...)
		sort.Slice(sortedEdges, func(a, b int) bool { return sortedEdges[a].Action < sortedEdges[b].Action })
		for _, e := range sortedEdges {
			alts = append(alts, fmt.Sprintf("%s -> %s", sanitizeFSPAct(e.Action), sanitizeFSPState(comp.States[e.Target])))
		}
		sb.WriteString(fmt.Sprintf("%s = (%s)%s\n", sname, strings.Join(alts, " | "), sep))
	}
}

func sanitizeFSPState(s string) string {
	r := strings.NewReplacer("[", "_", "]", "", "=", "_", ",", "_", " ", "")
	out := strings.ToUpper(r.Replace(s))
	if out == "END" || out == "STOP" || out == "ERROR" {
		return out
	}
	return "S_" + out
}

func sanitizeFSPAct(a string) string {
	if a == "tau" {
		return "tau"
	}
	return strings.ReplaceAll(a, " ", "_")
}
